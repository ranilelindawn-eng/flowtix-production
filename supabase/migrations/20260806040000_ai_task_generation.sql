create policy ai_task_suggestions_select_member on public.ai_task_suggestions
for select to authenticated
using (public.is_organization_member(organization_id));

drop policy if exists ai_task_suggestions_insert_member on public.ai_task_suggestions;
create policy ai_task_suggestions_insert_member on public.ai_task_suggestions
for insert to authenticated
with check (
  created_by = auth.uid()
  and public.is_organization_member(organization_id)
  and (contact_id is null or exists (select 1 from public.contacts c where c.id = contact_id and c.organization_id = organization_id))
  and (call_id is null or exists (select 1 from public.calls c where c.id = call_id and c.organization_id = organization_id))
  and (transcript_id is null or exists (select 1 from public.transcripts t where t.id = transcript_id and t.organization_id = organization_id))
);

drop policy if exists ai_task_suggestions_update_member on public.ai_task_suggestions;
create policy ai_task_suggestions_update_member on public.ai_task_suggestions
for update to authenticated
using (public.is_organization_member(organization_id))
with check (public.is_organization_member(organization_id));

drop policy if exists ai_task_suggestions_delete_member on public.ai_task_suggestions;
create policy ai_task_suggestions_delete_member on public.ai_task_suggestions
for delete to authenticated
using (created_by = auth.uid() or public.can_manage_organization_assignments(organization_id));

