create or replace function public.accept_ai_task_suggestion(
  target_organization_id uuid,
  target_suggestion_id uuid,
  target_assigned_to uuid default null
)
returns table(task_id uuid, reused boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_id uuid := auth.uid();
  suggestion public.ai_task_suggestions%rowtype;
  target_membership_id uuid;
  created_task_id uuid;
begin
  if actor_id is null then
    raise exception 'Authentication is required.' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.organization_members member
    where member.organization_id = target_organization_id
      and member.user_id = actor_id
      and member.status = 'active'
  ) then
    raise exception 'Active organization membership is required.' using errcode = '42501';
  end if;

  select * into suggestion
  from public.ai_task_suggestions item
  where item.id = target_suggestion_id
    and item.organization_id = target_organization_id
  for update;

  if not found then raise exception 'AI task suggestion was not found.'; end if;
  if suggestion.status = 'dismissed' then raise exception 'Dismissed suggestions cannot be accepted.'; end if;
  if suggestion.status = 'accepted' and suggestion.accepted_task_id is not null then
    return query select suggestion.accepted_task_id, true;
    return;
  end if;

  if target_assigned_to is not null then
    select member.id into target_membership_id
    from public.organization_members member
    where member.organization_id = target_organization_id
      and member.user_id = target_assigned_to
      and member.status = 'active'
    limit 1;
    if target_membership_id is null then
      raise exception 'The selected assignee is not an active organization member.';
    end if;
  else
    target_assigned_to := actor_id;
    select member.id into target_membership_id
    from public.organization_members member
    where member.organization_id = target_organization_id
      and member.user_id = actor_id
      and member.status = 'active'
    limit 1;
  end if;

  insert into public.contact_tasks (
    organization_id, contact_id, title, description, due_at, status, priority,
    assigned_to, owner_membership_id, created_by, completed_at
  ) values (
    target_organization_id,
    suggestion.contact_id,
    suggestion.title,
    suggestion.description,
    suggestion.suggested_due_at,
    'pending',
    suggestion.priority,
    target_assigned_to,
    target_membership_id,
    actor_id,
    null
  ) returning id into created_task_id;

  update public.ai_task_suggestions
  set status = 'accepted', accepted_at = now(), accepted_by = actor_id,
      accepted_task_id = created_task_id, dismissed_at = null, dismissed_by = null
  where id = suggestion.id;

  return query select created_task_id, false;
end;
$$;

